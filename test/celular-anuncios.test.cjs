'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), { randomUUID } = require('node:crypto'), { fork } = require('node:child_process');
const root = path.resolve(__dirname, '..'), dados = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'correa-celular-test-'));
process.env.PASTA_DADOS = dados;
const db = require('../db'); require('../anuncios');
const p = require('../publicacoes'), { criarGerenciador } = require('../envios-anuncios');
let child, verificacoes = 0;
const ok = (v,msg) => { assert.ok(v,msg); verificacoes++; };
const rejeita = (fn, status = 400) => { assert.throws(fn,e => e.status === status); verificacoes++; };
const imagem = fs.readFileSync(path.join(root,'public/img/logo.jpg'));
const foto = () => ({chave:randomUUID(),conteudo:imagem,tipoMime:'image/jpeg',nomeOriginal:'Foto de teste.jpg'});
async function main() {
  let horario = Date.now();
  const envios = criarGerenciador({agora: () => horario});
  const anuncio = p.criar({marca_modelo:'Veículo fictício',situacao:'publicado'}), outro = p.criar({marca_modelo:'Outro veículo fictício'});
  const envio = envios.criar(anuncio.id);
  ok(/^[\w-]{43}$/.test(envio.codigo), 'Código aleatório não contém o ID do anúncio');
  rejeita(() => envios.publico('invalido'),404);
  rejeita(() => envios.acompanhar(outro.id,envio.codigo),404);
  rejeita(() => envios.encerrar(outro.id,envio.codigo),404);
  rejeita(() => envios.enviar(envio.codigo,{...foto(),tipoMime:'application/pdf'}));
  rejeita(() => envios.enviar(envio.codigo,{...foto(),conteudo:Buffer.from('não é foto')}));
  rejeita(() => envios.enviar(envio.codigo,{...foto(),chave:''}));
  const arquivo = foto(); envios.enviar(envio.codigo,arquivo); envios.enviar(envio.codigo,arquivo);
  const recebidas = envios.acompanhar(anuncio.id,envio.codigo);
  ok(recebidas.recebidas === 1 && p.obter(anuncio.id).fotos_disponiveis.length === 1, 'Repetir o envio não duplica a foto');
  ok(p.publico(anuncio.id).fotos.length === 0, 'Receber pelo celular não modifica o anúncio público');
  const resumo = envios.publico(envio.codigo);
  ok(Object.keys(resumo).sort().join() === ['titulo','expira_em','recebidas','limite'].sort().join(), 'Celular não recebe fotos, IDs, documentos ou dados internos');
  ok(envios.encerrar(anuncio.id,envio.codigo).fotos.length === 1, 'Concluir captura também a última foto recebida');
  rejeita(() => envios.enviar(envio.codigo,foto()),404);
  const velho = envios.criar(anuncio.id), novo = envios.criar(anuncio.id);
  rejeita(() => envios.publico(velho.codigo),404);
  horario += 3600e3;
  rejeita(() => envios.publico(novo.codigo),404);
  rejeita(() => envios.enviar(novo.codigo,foto()),404);
  const limite = envios.criar(anuncio.id);
  for (let i=0;i<40;i++) envios.enviar(limite.codigo,foto());
  rejeita(() => envios.enviar(limite.codigo,foto()),409);
  ok(envios.publico(limite.codigo).recebidas === 40, 'Limite de fotos aplicado no servidor');
  require('../auth').criarUsuario({nome:'Equipe fictícia',usuario:'teste-celular',senha:'TesteLocal123'});
  child = fork(path.join(__dirname,'fixtures/servidor.cjs'),[],{cwd:root,env:{...process.env,SITE_TEST_ROOT:root},silent:true});
  let erroServidor=''; child.stderr.on('data',b => { erroServidor += b; });
  const porta = await new Promise((resolve,reject) => { const timer=setTimeout(() => reject(new Error(erroServidor || 'Servidor não iniciou')),20000); child.once('message',m => {clearTimeout(timer);resolve(m.port);}); child.once('exit',() => reject(new Error(erroServidor))); });
  const base='http://127.0.0.1:'+porta;
  let cookie='';
  const req=(metodo,url,corpo,logado=true) => fetch(base+url,{method:metodo,redirect:'manual',headers:{...(logado?{Cookie:cookie}:{}),...(corpo?{'Content-Type':'application/json'}:{})},body:corpo?JSON.stringify(corpo):undefined});
  const rota=`/api/site/publicacoes/${outro.id}/celular`;
  ok((await req('POST',rota,{},false)).status === 401,'Criar QR exige login');
  let r=await req('POST','/api/login',{usuario:'teste-celular',senha:'TesteLocal123'},false); cookie=r.headers.get('set-cookie').split(';')[0];
  r=await req('POST',rota,{}); const qr=await r.json(); ok(r.status===200 && qr.url.startsWith(base+'/fotos-anuncio.html?c='),'Link usa o endereço público da instalação');
  const publico='/api/anuncios-celular/'+qr.codigo;
  r=await req('GET',publico,undefined,false); ok(r.status===200 && !(await r.json()).fotos,'Celular acessa somente o resumo sem login');
  ok((await req('GET',rota+'/'+qr.codigo,undefined,false)).status===401,'Lista de fotos exige login');
  ok((await req('POST',rota+'/'+qr.codigo+'/encerrar',{},false)).status===401,'Encerrar exige login');
  r=await req('POST',publico+'/fotos',{chave:randomUUID(),base64:imagem.toString('base64'),tipo_mime:'image/jpeg',nome:'Foto.jpg',publicacao_id:anuncio.id},false);
  const enviado=await r.json(); ok(r.status===200 && enviado.ok && !enviado.url && !enviado.id,'Resposta do envio não divulga arquivo nem permite trocar o anúncio');
  r=await req('GET',rota+'/'+qr.codigo); const resultado=await r.json();
  ok(resultado.fotos.length===1 && resultado.fotos[0].url.startsWith('/anexos/'),'Computador recebe a foto privada vinculada ao anúncio correto');
  ok((await req('GET',resultado.fotos[0].url,undefined,false)).status===302,'Link do celular não permite consultar anexos privados');
  ok((await req('GET',`/midia/anuncios/${outro.id}/${resultado.fotos[0].id}`,undefined,false)).status===404,'Foto recebida continua fora do site');
  ok((await req('POST',rota+'/'+qr.codigo+'/encerrar',{})).status===200,'Computador encerra o envio');
  ok((await req('GET',publico,undefined,false)).status===404,'Código encerrado deixa de funcionar');
  r=await req('GET','/fotos-anuncio.html',undefined,false);
  ok(r.status===200 && r.headers.get('referrer-policy')==='no-referrer' && r.headers.get('cache-control')==='no-store','Página móvel pública sem cache nem envio de referência');
  ok((await req('GET','/fotos-anuncio.js',undefined,false)).status===200,'Script do celular acessível sem login');
  console.log(JSON.stringify({ok:true,verificacoes}));
}
main().catch(e => {console.error(e);process.exitCode=1;}).finally(async () => {
  if (child && child.exitCode===null) {const fim=new Promise(resolve => child.once('exit',resolve));child.kill();await fim;}
  db.conexao.close();fs.rmSync(dados,{recursive:true,force:true});
});
